def normalize_chapter(path_str: str, intro: str) -> None:
    path = ROOT / path_str
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if not lines or not lines[0].startswith("# "):
        raise RuntimeError(f"missing chapter title: {path_str}")
    title = lines[0]
    marker = "\n---\n"
    marker_pos = text.find(marker)
    if marker_pos < 0:
        raise RuntimeError(f"missing first separator: {path_str}")
    rest = text[marker_pos + len(marker):]

    # A chapter title is the only H1. If the old body used H1 main sections,
    # shift the complete body hierarchy down by one level.
    if re.search(r"^# ", rest, flags=re.MULTILINE):
        rest = re.sub(
            r"^(#{1,5}) ",
            lambda m: "#" + m.group(1) + " ",
            rest,
            flags=re.MULTILINE,
        )

    new_text = title + "\n\n" + intro.strip() + "\n\n---\n\n" + rest.lstrip("\n")
    path.write_text(new_text, encoding="utf-8")


